  /// توحيد اختلافات كتابة الاسم العربي قبل المقارنة لمنع تكرار الأشخاص.
  static String normalizeName(String value) {
    return value
        .replaceAll(RegExp(r'[\u064B-\u065F\u0670\u0640]'), '')
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ى', 'ي')
        .replaceAll('ة', 'ه')
        .replaceAll(RegExp(r'\s+'), '')
        .trim();
  }

  static bool isSupervisor(String name) {
    final normalized = normalizeName(name);
    return supervisors.any((person) => normalizeName(person) == normalized);
  }

  static bool isClinicOfficer(String name) {
    final normalized = normalizeName(name);
    const rosterAliases = {
      'كاتب محمد محمود بني خالد': 'كاتب محمد محمود الخالدي',
    };
    final canonical = rosterAliases[name] ?? name;
    final canonicalNormalized = normalizeName(canonical);
    return clinicOfficers.any((person) =>
        normalizeName(person) == normalized ||
        normalizeName(person) == canonicalNormalized);
  }

  /// الأسماء الأصلية تبقى محفوظة كما هي، وتُستبعد فئاتها من الاختيار الأمني.
  static List<String> officersFor(String shift, {
    bool clinicReplacement = false,
    bool excludeClinicOfficers = true,
  }) {
    final values = <String>{...shiftA, ...shiftB, ...shiftC};
    final result = values.where((name) {
      if (isSupervisor(name)) return false;
      if (!clinicReplacement && excludeClinicOfficers && isClinicOfficer(name)) return false;
      return true;
    }).toList()
      ..sort((a, b) => a.compareTo(b));
    return result;
  }

